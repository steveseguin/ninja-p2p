 await assert.rejects(call(a,'send_message',{...args,text:'changed'}),/idempotency_conflict/);
 let messages=await call(b,'read_messages');assert.deepEqual(messages.messages.map(m=>m.id),[first.id,second.id]);assert.equal(messages.next_sequence,2);
 assert.equal((await call(c,'read_messages')).messages.length,0);
 await assert.rejects(call(c,'reply_to_message',{message_id:first.id,text:'cross-owner'}),/not_found/);
